#!/usr/bin/env bash
# Run by the wazuh-manager image on every start (/entrypoint-scripts/*.sh), after the
# Filebeat configuration and before the Wazuh and Filebeat daemons are launched.
set -euo pipefail

FB=/etc/filebeat/filebeat.yml


# 1. Archives: index ALL events (archives.json -> wazuh-archives-4.x-*).
#    The file is rewritten from the image on every start, so it is changed every time.
sed -i '/^    archives:/{n;s/enabled: false/enabled: true/}' "$FB"

# 2. Filebeat: removes the "Answer"/"OrigAnswer" field of the AdGuard log (DNS answer packed in
#    base64, large and useless) before sending to the indexer. JSON decoding happens in the
#    indexer's ingest pipeline: the raw text is therefore changed, including its escaped copy
#    in full_log.
if ! grep -q watchpost_strip_dns_answer "$FB"; then
  cat >>"$FB" <<'EOT'

processors:
  - script:
      lang: javascript
      id: watchpost_strip_dns_answer
      source: >
        function process(event) {
          var m = event.Get("message");
          if (typeof m === "string" && m.indexOf('Answer') !== -1) {
            event.Put("message", m.replace(/,\\?"(Orig)?Answer\\?":\\?"[A-Za-z0-9+\/=]*\\?"/g, ""));
          }
        }
EOT
fi

# 2b. Throughput: the queue between wazuh-logcollector and analysis (1024 lines by default)
#     overflows when the collector exports at once the buffer of a phone that stayed offline
#     ("Target 'agent' message queue is full… Log lines may be lost", seen in testing with 3 h of history).
# 2c. Correlation: with several analysis threads (default: one per CPU), events received in the
#     same millisecond are evaluated in parallel and do not see each other; the correlation rules
#     (100489: collector detections, written in bursts; 100502: app.risk after app.installed)
#     missed them (seen in the v1.2 test). A single thread: file order respected; largely enough
#     for a few phones (throughput measured in infra/README.md §11.2).
printf '%s\n' "# Generated by watchpost-init.sh on every start." "logcollector.queue_size=65536" \
  "analysisd.event_threads=1" "analysisd.rule_matching_threads=1" \
  >/var/ossec/etc/local_internal_options.conf
chown root:wazuh /var/ossec/etc/local_internal_options.conf
chmod 640 /var/ossec/etc/local_internal_options.conf

# 3. CDB list of the expected private DNS hosts (rule 100195).
LIST=/var/ossec/etc/lists/watchpost-private-dns-hosts
: >"$LIST"
for h in ${WATCHPOST_PRIVATE_DNS_HOSTS:-}; do
  printf '%s:\n' "$h" >>"$LIST"
done
[[ -s "$LIST" ]] || printf 'dns.invalid:\n' >>"$LIST"
chown wazuh:wazuh "$LIST"
chmod 660 "$LIST"

# 4. Random agent enrollment password (no Wazuh agent is planned).
if [[ ! -s /var/ossec/etc/authd.pass ]]; then
  head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n' >/var/ossec/etc/authd.pass
  chown root:wazuh /var/ossec/etc/authd.pass
  chmod 640 /var/ossec/etc/authd.pass
fi

# 5. Watchpost rules: owner expected by wazuh-analysisd.
chown wazuh:wazuh /var/ossec/etc/rules/watchpost_*.xml 2>/dev/null || true
chmod 660 /var/ossec/etc/rules/watchpost_*.xml 2>/dev/null || true

# 6. Retention of the raw archives on disk (daily archives.json.gz, never purged by Wazuh): the
#    data stays in the indexer, subject to the ISM policy.
find /var/ossec/logs/archives -type f -name '*.gz' -mtime +"${WATCHPOST_ARCHIVES_FILE_DAYS:-14}" -delete 2>/dev/null || true
find /var/ossec/logs/alerts -type f -name '*.gz' -mtime +"${WATCHPOST_ARCHIVES_FILE_DAYS:-14}" -delete 2>/dev/null || true

# 7. Optional notifications (ntfy-compatible webhook, SMTP e-mail): Wazuh integration
#    "custom-watchpost-notify" for alerts of level >= WATCHPOST_NOTIFY_LEVEL and for the agent
#    silence (100301) and the sequence reset (100305). ossec.conf is copied again on every
#    start: without configuration, no integration exists.
NOTIFY_CONF=/var/ossec/etc/watchpost-notify.json
if [[ -n "${WATCHPOST_NOTIFY_URL:-}${WATCHPOST_NOTIFY_SMTP_HOST:-}" ]]; then
  LEVEL="${WATCHPOST_NOTIFY_LEVEL:-10}"
  [[ "$LEVEL" =~ ^[0-9]+$ ]] || LEVEL=10
  install -o root -g wazuh -m 750 /watchpost/notify/custom-watchpost-notify /watchpost/notify/custom-watchpost-notify.py \
    /var/ossec/integrations/
  /var/ossec/framework/python/bin/python3 - "$NOTIFY_CONF" <<'PY'
import json, os, sys
e = os.environ.get
conf = {"url": e("WATCHPOST_NOTIFY_URL", ""), "topic": e("WATCHPOST_NOTIFY_TOPIC", ""), "token": e("WATCHPOST_NOTIFY_TOKEN", ""),
        "smtp_host": e("WATCHPOST_NOTIFY_SMTP_HOST", ""), "smtp_port": e("WATCHPOST_NOTIFY_SMTP_PORT", "587"),
        "smtp_tls": e("WATCHPOST_NOTIFY_SMTP_TLS", "starttls"), "smtp_user": e("WATCHPOST_NOTIFY_SMTP_USER", ""),
        "smtp_password": e("WATCHPOST_NOTIFY_SMTP_PASSWORD", ""), "smtp_from": e("WATCHPOST_NOTIFY_SMTP_FROM", ""),
        "smtp_to": e("WATCHPOST_NOTIFY_SMTP_TO", "")}
with open(sys.argv[1], "w") as f:
    json.dump(conf, f)
PY
  chown root:wazuh "$NOTIFY_CONF"
  chmod 640 "$NOTIFY_CONF"
  # Monitoring rules below the chosen threshold (silence: 7, sequence reset: 8).
  EXTRA=""
  ((LEVEL > 7)) && EXTRA="100301"
  ((LEVEL > 8)) && EXTRA="$EXTRA,100305"
  {
    echo "<ossec_config>"
    printf '  <integration>\n    <name>custom-watchpost-notify</name>\n    <level>%s</level>\n    <alert_format>json</alert_format>\n  </integration>\n' "$LEVEL"
    if [[ -n "$EXTRA" ]]; then
      printf '  <integration>\n    <name>custom-watchpost-notify</name>\n    <rule_id>%s</rule_id>\n    <alert_format>json</alert_format>\n  </integration>\n' "${EXTRA#,}"
    fi
    echo "</ossec_config>"
  } >>/var/ossec/etc/ossec.conf
  echo "watchpost-init: notifications active (level >= $LEVEL${EXTRA:+, rules $EXTRA})"
else
  rm -f "$NOTIFY_CONF"
fi

echo "watchpost-init: Watchpost configuration applied"
